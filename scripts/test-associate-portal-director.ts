import assert from 'node:assert/strict';
import {setAssociateStatus,setWorkCategories,setClientAccreditation,recordInductionApproval,prepareAssociateInvitation} from '../server/associatePortalDirector.js';
import type {PortalStore} from '../server/associatePortalStore.js';
const actor={id:'director@example.org',role:'director' as const,authenticated:true as const};
const initial:PortalStore={version:1,accounts:[{registrationId:'TEST-01',email:'associate@example.org',eligibility:{status:'applicant',induction:'not-started',approvedCategories:[],clientAccreditation:'not-assessed'}}],invitations:[]};
assert.throws(()=>setAssociateStatus(initial,{} as any,'TEST-01','approved','reviewed'),/authentication/);
const approved=setAssociateStatus(initial,actor,'TEST-01','approved','identity checked');
assert.equal(initial.accounts[0].eligibility.status,'applicant');
assert.equal(approved.accounts[0].eligibility.status,'approved');
assert.throws(()=>prepareAssociateInvitation(initial,actor,'TEST-01'),/approved/);
const assigned=setWorkCategories(approved,actor,'TEST-01',['Digital','Digital','PMO']);
assert.deepEqual(assigned.accounts[0].eligibility.approvedCategories,['Digital','PMO']);
assert.throws(()=>setClientAccreditation(assigned,actor,'TEST-01','approved','certificate'),/induction/);
const inducted=recordInductionApproval(assigned,actor,'TEST-01','IND-100','2026-10-14T12:00:00Z');
assert.equal(inducted.accounts[0].eligibility.induction,'passed');
assert.equal(inducted.accounts[0].inductionEvidence?.assessor,actor.id);
assert.throws(()=>setClientAccreditation(inducted,actor,'TEST-01','approved',''),/evidence/);
const accredited=setClientAccreditation(inducted,actor,'TEST-01','approved','CERT-01');
assert.equal(accredited.accounts[0].eligibility.clientAccreditation,'approved');
const {store:invited,token}=prepareAssociateInvitation(accredited,actor,'TEST-01',Date.parse('2026-10-14T12:00:00Z'));
assert.equal(token.length,64);
assert.equal(invited.invitations.length,1);
const suspended=setAssociateStatus(invited,actor,'TEST-01','suspended','temporary suspension');
assert.ok(suspended.invitations[0].revokedAt!==null);
const revoked=setAssociateStatus(invited,actor,'TEST-01','revoked','access withdrawn');
assert.throws(()=>setAssociateStatus(revoked,actor,'TEST-01','approved','undo'),/separate identity verification/);
assert.equal(invited.accounts[0].eligibility.status,'approved');
console.log('Associate Portal Director command checks passed');
